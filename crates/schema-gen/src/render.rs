use std::fmt::Write as _;
use std::{collections::BTreeMap, path::PathBuf};

use prost_types::{DescriptorProto, FileDescriptorSet, field_descriptor_proto::Type};

use super::{
    GENERATED, GENERATED_DIR,
    accessors::render_accessors,
    codegen::{
        encode_scalar_type, enum_variant, format_rust, handler_type, ordered_fields, pascal,
        sanitize, snake, to_upper,
    },
    model::Policy,
    scanner::render_scanner,
    writer::render_writer,
};

type Outputs = BTreeMap<PathBuf, Vec<u8>>;
type MessageIndex<'a> = BTreeMap<String, &'a DescriptorProto>;

pub(super) fn render(set: &FileDescriptorSet, policy: &Policy) -> Result<Outputs, String> {
    let file = &set.file[0];
    let messages = message_index(&policy.package, &file.message_type);
    let mut outputs = Outputs::new();
    let mut main = main_prelude();
    render_field_specs(file, policy, &messages, &mut main, &mut outputs)?;
    append_scanner(policy, &mut main, &mut outputs)?;
    render_enums(policy, &mut main, &mut outputs)?;
    render_validated_types(policy, &mut main, &mut outputs)?;
    append_accessors(policy, &mut main, &mut outputs)?;
    render_handlers(policy, &mut main, &mut outputs)?;
    append_writer(policy, &mut main, &mut outputs)?;
    outputs.insert(PathBuf::from(GENERATED), format_rust(main.as_bytes())?);
    Ok(outputs)
}

fn main_prelude() -> String {
    String::from(
        "// @generated by crates/schema-gen; do not edit.\n\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub(super) enum WireKind { Varint, Fixed64, LengthDelimited, Fixed32 }\n#[derive(Clone, Copy, Debug)]\npub(super) struct FieldSpec { pub id: u8, pub message: &'static str, pub name: &'static str, pub tag: u32, pub kind: WireKind, pub repeated: bool, pub required: bool, pub type_name: Option<&'static str>, pub constraints: &'static [&'static str], pub oneof: Option<&'static str> }\n\n\n\n",
    )
}

fn message_index<'a>(package: &str, descriptors: &'a [DescriptorProto]) -> MessageIndex<'a> {
    fn visit<'a>(prefix: &str, descriptors: &'a [DescriptorProto], output: &mut MessageIndex<'a>) {
        for descriptor in descriptors {
            let name = descriptor.name.as_deref().unwrap_or("");
            let full_name = if prefix.is_empty() {
                name.to_owned()
            } else {
                format!("{prefix}.{name}")
            };
            output.insert(full_name.clone(), descriptor);
            visit(&full_name, &descriptor.nested_type, output);
        }
    }
    let mut output = MessageIndex::new();
    visit(package, descriptors, &mut output);
    output
}

fn render_field_specs(
    file: &prost_types::FileDescriptorProto,
    policy: &Policy,
    messages: &MessageIndex<'_>,
    main: &mut String,
    outputs: &mut Outputs,
) -> Result<(), String> {
    let mut ids = BTreeMap::new();
    let mut next_id = 0u16;
    for short in policy.messages.keys() {
        let descriptor = messages[&format!("{}.{}", policy.package, short)];
        let mut fields: Vec<_> = descriptor.field.iter().collect();
        fields.sort_by_key(|field| field.number.unwrap_or_default());
        for field in fields {
            let name = field.name.as_deref().ok_or("unnamed descriptor field")?;
            if next_id > u16::from(u8::MAX) {
                return Err("wire path field ID capacity exceeds 256 generated fields".into());
            }
            ids.insert(
                (short.as_str(), name),
                u8::try_from(next_id).map_err(|_| "wire path field ID overflow")?,
            );
            next_id += 1;
        }
    }
    let mut field_names = vec!["<unknown-field>"; ids.len()];
    for ((_, name), id) in &ids {
        field_names[usize::from(*id)] = name;
    }
    let names = field_names
        .iter()
        .map(|name| format!("{name:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        main,
        "const FIELD_NAMES: [&str; {}] = [{names}];\npub(super) fn field_name(id: u8) -> &'static str {{ FIELD_NAMES.get(usize::from(id)).copied().unwrap_or(\"<unknown-field>\") }}",
        field_names.len()
    );
    for (short, message) in &policy.messages {
        let descriptor = messages[&format!("{}.{}", policy.package, short)];
        let mut fields: Vec<_> = descriptor.field.iter().collect();
        fields.sort_by_key(|field| field.number.unwrap_or_default());
        let mut body = format!(
            "// @generated field metadata for {short}.\npub(super) const FIELDS_{}: &[FieldSpec] = &[\n",
            to_upper(short)
        );
        for field in fields {
            let name = field.name.as_deref().ok_or("unnamed descriptor field")?;
            append_field_spec(&mut body, short, message, field, ids[&(short.as_str(), name)]);
        }
        body.push_str("];\n");
        let file_name = format!("fields_{}.rs", snake(short));
        insert_generated(outputs, &file_name, &body)?;
        let _ = writeln!(main, "include!(\"generated/{file_name}\");");
    }
    let _ = file;
    Ok(())
}

fn append_field_spec(
    body: &mut String,
    message_name: &str,
    message: &super::model::MessagePolicy,
    field: &prost_types::FieldDescriptorProto,
    id: u8,
) {
    let name = field.name.as_deref().unwrap_or("");
    let policy = &message.fields[name];
    let wire = match field.r#type() {
        Type::Double | Type::Fixed64 | Type::Sfixed64 => "Fixed64",
        Type::Float | Type::Fixed32 | Type::Sfixed32 => "Fixed32",
        Type::Int64
        | Type::Uint64
        | Type::Int32
        | Type::Bool
        | Type::Uint32
        | Type::Enum
        | Type::Sint32
        | Type::Sint64 => "Varint",
        _ => "LengthDelimited",
    };
    let oneof = policy
        .oneof
        .as_ref()
        .map_or_else(|| "None".into(), |name| format!("Some({name:?})"));
    let type_name = policy
        .type_name
        .as_ref()
        .map_or_else(|| "None".into(), |name| format!("Some({name:?})"));
    let constraints = policy
        .constraints
        .iter()
        .map(|constraint| format!("{constraint:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        body,
        "    FieldSpec {{ id: {id}, message: {message_name:?}, name: {name:?}, tag: {}u32, kind: WireKind::{wire}, repeated: {}, required: {}, type_name: {type_name}, constraints: &[{constraints}], oneof: {oneof} }},",
        policy.tag,
        policy.cardinality == "repeated",
        policy.presence == "required",
    );
}

fn append_scanner(policy: &Policy, main: &mut String, outputs: &mut Outputs) -> Result<(), String> {
    for (name, bytes) in render_scanner(policy)? {
        outputs.insert(PathBuf::from(GENERATED_DIR).join(name), bytes);
    }
    main.push_str("include!(\"generated/scanner.rs\");\n");
    Ok(())
}

fn render_enums(policy: &Policy, main: &mut String, outputs: &mut Outputs) -> Result<(), String> {
    for (name, values) in &policy.enums {
        let mut body = format!(
            "// @generated enum mapping for {name}.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub(super) enum {name} {{\n"
        );
        for value in values.iter().filter(|value| value.accepted) {
            let _ = writeln!(body, "    {},", enum_variant(&value.name, name));
        }
        append_enum_conversions(&mut body, name, values);
        let file_name = format!("enum_{}.rs", snake(name));
        insert_generated(outputs, &file_name, &body)?;
        let _ = writeln!(main, "include!(\"generated/{file_name}\");");
    }
    Ok(())
}

fn append_enum_conversions(body: &mut String, name: &str, values: &[super::model::EnumValue]) {
    body.push_str("}\n");
    let _ = writeln!(
        body,
        "impl {name} {{ pub(super) fn from_wire(value: i32) -> Option<Self> {{ match value {{"
    );
    for value in values.iter().filter(|value| value.accepted) {
        let _ = writeln!(
            body,
            "    {} => Some(Self::{}),",
            value.number,
            enum_variant(&value.name, name)
        );
    }
    body.push_str("    _ => None,\n} } }\n");
    let _ = writeln!(
        body,
        "impl {name} {{ pub(super) fn to_wire(self) -> i32 {{ match self {{"
    );
    for value in values.iter().filter(|value| value.accepted) {
        let _ = writeln!(
            body,
            "    Self::{} => {},",
            enum_variant(&value.name, name),
            value.number
        );
    }
    body.push_str("} } }\n");
}

fn render_validated_types(
    policy: &Policy,
    main: &mut String,
    outputs: &mut Outputs,
) -> Result<(), String> {
    for name in policy.messages.keys() {
        let file_name = format!("validated_{}.rs", snake(name));
        let extra = if name == "Sample" {
            "summary: ScanSummary, "
        } else {
            ""
        };
        let body = if policy.messages[name].fields.is_empty() {
            format!(
                "// @generated validated marker for empty message {name}.\n#[derive(Clone, Copy, Debug)]\npub(super) struct Validated{name} {{ _private: () }}\n"
            )
        } else {
            format!(
                "// @generated validated borrowed view for {name}.\n#[derive(Clone, Copy, Debug)]\npub(super) struct Validated{name}<'a> {{ span: Span<'a>, {extra}}}\n"
            )
        };
        insert_generated(outputs, &file_name, &body)?;
        let _ = writeln!(main, "include!(\"generated/{file_name}\");");
    }
    Ok(())
}

fn append_accessors(
    policy: &Policy,
    main: &mut String,
    outputs: &mut Outputs,
) -> Result<(), String> {
    for (name, bytes) in render_accessors(policy)? {
        outputs.insert(PathBuf::from(GENERATED_DIR).join(name), bytes);
    }
    main.push_str("include!(\"generated/accessors.rs\");\n");
    Ok(())
}

fn render_handlers(
    policy: &Policy,
    main: &mut String,
    outputs: &mut Outputs,
) -> Result<(), String> {
    for (short, message) in &policy.messages {
        let body = render_handler_file(short, message, policy);
        let file_name = format!("handlers_{}.rs", snake(short));
        insert_generated(outputs, &file_name, &body)?;
        let _ = writeln!(main, "include!(\"generated/{file_name}\");");
    }
    Ok(())
}

pub(super) fn render_handler_file(
    short: &str,
    message: &super::model::MessagePolicy,
    policy: &Policy,
) -> String {
    let trait_name = pascal(short);
    let empty_message = message.fields.is_empty();
    let mut body = if empty_message {
        format!("// @generated required handlers for {short}.\npub(super) trait Decode{trait_name} {{ type Error: From<DecodeError>;\n")
    } else {
        format!("// @generated required handlers for {short}.\npub(super) trait Decode{trait_name}<'a> {{ type Error: From<DecodeError>;\n")
    };
    append_decode_handlers(&mut body, short, message, policy);
    body.push_str("}\n");
    let _ = writeln!(body, "pub(super) trait Encode{trait_name} {{");
    append_encode_handlers(&mut body, message);
    body.push_str("}\n");
    body
}

fn append_decode_handlers(
    body: &mut String,
    short: &str,
    message: &super::model::MessagePolicy,
    policy: &Policy,
) {
    for (field, field_policy) in ordered_fields(message) {
        let ty = handler_type(short, field, field_policy, &policy.messages);
        let _ = writeln!(
            body,
            "    fn {}(&mut self, value: {ty}) -> Result<(), Self::Error>;",
            sanitize(&field_policy.handler)
        );
    }
    for constraint in &message.constraints {
        if policy.constraints[constraint].phase == "mapping" {
            let method = snake(constraint);
            let _ = writeln!(
                body,
                "    fn {method}(&mut self, value: Validated{short}<'a>) -> Result<(), Self::Error>;"
            );
        }
    }
}

fn append_encode_handlers(body: &mut String, message: &super::model::MessagePolicy) {
    for (field, field_policy) in ordered_fields(message) {
        let method = sanitize(field);
        let assoc = pascal(field);
        let base = encode_scalar_type(&field_policy.kind, field_policy.type_name.as_deref(), false);
        if field_policy.cardinality == "repeated" {
            append_repeated_encode_handler(body, &assoc, field_policy);
            let _ = writeln!(body, "    fn {method}(&self) -> Self::{assoc}<'_>;");
        } else if field_policy.kind == "message" {
            append_message_encode_handler(body, &method, &assoc, field_policy);
        } else {
            let ty = if field_policy.oneof.is_some() || field_policy.presence == "optional" {
                format!("Option<{base}>")
            } else {
                base
            };
            let _ = writeln!(body, "    fn {method}(&self) -> {ty};");
        }
    }
}

fn append_repeated_encode_handler(
    body: &mut String,
    assoc: &str,
    field: &super::model::FieldPolicy,
) {
    if field.kind == "message" {
        let child = field.type_name.as_deref().unwrap_or("Message");
        let _ = write!(
            body,
            "    type {assoc}<'a>: Iterator<Item = Self::{assoc}Item<'a>> where Self: 'a;\n    type {assoc}Item<'a>: Encode{child} where Self: 'a;\n"
        );
    } else {
        let item = encode_scalar_type(&field.kind, field.type_name.as_deref(), true);
        let _ = writeln!(
            body,
            "    type {assoc}<'a>: Iterator<Item = {item}> where Self: 'a;"
        );
    }
}

fn append_message_encode_handler(
    body: &mut String,
    method: &str,
    assoc: &str,
    field: &super::model::FieldPolicy,
) {
    let child = field.type_name.as_deref().unwrap_or("Message");
    let _ = writeln!(body, "    type {assoc}<'a>: Encode{child} where Self: 'a;");
    if field.presence == "optional" || field.oneof.is_some() {
        let _ = writeln!(
            body,
            "    fn {method}(&self) -> Option<Self::{assoc}<'_>>;"
        );
    } else {
        let _ = writeln!(body, "    fn {method}(&self) -> Self::{assoc}<'_>;");
    }
}

fn append_writer(policy: &Policy, main: &mut String, outputs: &mut Outputs) -> Result<(), String> {
    let (writer_root, writer_files) = render_writer(&policy.messages)?;
    for (name, contents) in writer_files {
        outputs.insert(
            PathBuf::from(GENERATED_DIR).join(name),
            format_rust(contents.as_bytes())?,
        );
    }
    outputs.insert(
        PathBuf::from(GENERATED_DIR).join("writer.rs"),
        format_rust(writer_root.as_bytes())?,
    );
    main.push_str("include!(\"generated/writer.rs\");\n");
    Ok(())
}

fn insert_generated(outputs: &mut Outputs, name: &str, source: &str) -> Result<(), String> {
    outputs.insert(
        PathBuf::from(GENERATED_DIR).join(name),
        format_rust(source.as_bytes())?,
    );
    Ok(())
}
